def _legacy_db(path: Path) -> Path:
    conn = sqlite3.connect(path)
    conn.executescript(LEGACY_DDL)
    for stmt in SEED:
        conn.execute(stmt)
    conn.commit()
    conn.close()
    return path


def _dump(path: Path) -> dict[str, list[tuple]]:
    conn = sqlite3.connect(path)
    try:
        return {t: conn.execute(f"SELECT * FROM {t} ORDER BY rowid").fetchall() for t in LEGACY_TABLES}
    finally:
        conn.close()


def _check_no_drift(db: Database) -> None:
    command.check(alembic_config(engine=db.engine))  # raises AutogenerateDiffsDetected on drift


def _cascade_fks(db: Database) -> set[tuple[str, str, str]]:
    with db.engine.connect() as conn:
        out = set()
        for table in ("conversations", "messages"):
            for row in conn.exec_driver_sql(f"PRAGMA foreign_key_list({table})"):
                out.add((table, row[2], row[6]))  # (table, referenced table, on_delete)
        return out


EXPECTED_FKS = {("conversations", "bots", "CASCADE"), ("messages", "conversations", "CASCADE")}


def test_fresh_database(tmp_path):
    db = Database(tmp_path / "fresh.db")
    run_migrations(db)
    tables = set(inspect(db.engine).get_table_names())
    assert tables == set(LEGACY_TABLES) | {"alembic_version"}
    assert current_revision(db.engine) == head_revision() == "0001_legacy_baseline"
    assert not list(tmp_path.glob("*.bak"))
    assert _cascade_fks(db) == EXPECTED_FKS
    _check_no_drift(db)


def test_adopts_legacy_database_without_data_changes(tmp_path):
    path = _legacy_db(tmp_path / "arena.db")
    before = _dump(path)
    assert all(before[t] for t in LEGACY_TABLES), "seed every table"

    db = Database(path)
    run_migrations(db)

    assert _dump(path) == before
    assert current_revision(db.engine) == head_revision()
    backups = list(tmp_path.glob("arena.db.pre-alembic-*.bak"))
    assert len(backups) == 1
    assert _dump(backups[0]) == before
    assert _cascade_fks(db) == EXPECTED_FKS
    _check_no_drift(db)


def test_second_upgrade_is_a_noop(tmp_path):
    path = _legacy_db(tmp_path / "arena.db")
    db = Database(path)
    run_migrations(db)
    after_first = _dump(path)
    run_migrations(db)
    assert _dump(path) == after_first
    assert len(list(tmp_path.glob("*.bak"))) == 1  # no second backup once alembic_version exists


def test_partial_legacy_database_gets_missing_tables(tmp_path):
    """An install that never used bots has only the key-store tables; the baseline adds the rest."""
    path = tmp_path / "arena.db"
    conn = sqlite3.connect(path)
    conn.executescript(LEGACY_DDL.split("CREATE TABLE IF NOT EXISTS bots")[0])
    conn.execute(SEED[0])
    conn.commit()
    conn.close()
    db = Database(path)
    run_migrations(db)
    assert set(inspect(db.engine).get_table_names()) >= set(LEGACY_TABLES)
    assert _dump(path)["api_keys"][0][1] == "main"


@pytest.mark.parametrize("legacy", [False, True])
def test_cli_upgrade_and_check(tmp_path, legacy, monkeypatch):
    """`alembic upgrade head` / `alembic check` as CI runs them, via -x db_path."""
    path = tmp_path / "cli.db"
    if legacy:
        _legacy_db(path)
    cfg = alembic_config()
    cfg.attributes.pop("engine")
    cfg.cmd_opts = type("Opts", (), {"x": [f"db_path={path}"]})()
    command.upgrade(cfg, "head")
    command.check(cfg)
    assert current_revision(Database(path).engine) == head_revision()
