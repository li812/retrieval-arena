    "INSERT INTO history (question, backend, collection, payload, pinned) VALUES ('q1', 'chroma', 'docs', '{}', 1)",
    "INSERT INTO history (question, backend, collection, payload) VALUES ('q2', 'graph', 'docs', '{\"a\": 1}')",
